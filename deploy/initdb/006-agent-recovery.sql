-- Agent lease recovery and durable graph checkpoints.
ALTER TABLE agent_run ADD COLUMN IF NOT EXISTS attempt_count INTEGER NOT NULL DEFAULT 0;
ALTER TABLE agent_run ADD COLUMN IF NOT EXISTS lease_owner VARCHAR(128);
ALTER TABLE agent_run ADD COLUMN IF NOT EXISTS lease_token VARCHAR(36);
ALTER TABLE agent_run ADD COLUMN IF NOT EXISTS lease_expires_at TIMESTAMP WITH TIME ZONE;

CREATE INDEX IF NOT EXISTS idx_agent_run_runnable
    ON agent_run (run_status, lease_expires_at, created_at);

CREATE TABLE IF NOT EXISTS graph_checkpoint (
    graph_id VARCHAR(128) NOT NULL,
    thread_id VARCHAR(128) NOT NULL,
    checkpoint_id VARCHAR(36) NOT NULL,
    checkpoint_order BIGINT GENERATED BY DEFAULT AS IDENTITY,
    node_id VARCHAR(128),
    next_node_id VARCHAR(128),
    state_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (graph_id, thread_id, checkpoint_id)
);

CREATE INDEX IF NOT EXISTS idx_graph_checkpoint_history
    ON graph_checkpoint (graph_id, thread_id, checkpoint_order DESC);
